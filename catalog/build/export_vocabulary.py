"""Write the database's current vocabulary to `curation/source/`, so a rebuild carries it.

The 148-subject baseline is source-built (`episode-themes/_vocabulary.json` plus
`subject-themes.json`). Everything after that baseline lived only in the database: the
Phase 3 relabel created 52 subjects through `create_subject` edits, retired one, and
rewrote descriptions on baseline subjects (`mass-shooting` past firearms,
`organised-crime` past drugs). None of that replays on a clean rebuild --
`replay.apply_all` reads the `edits` table, which is empty without `--carry-edits`, and
its own contract says creations are not replayable. So a rebuild produced 148 subjects
and dropped 6,411 label rows pointing at the other 52.

This exports the *entire* current vocabulary -- every live subject's slug, name,
description and theme, plus retirements -- to `vocabulary-current.json`.
`vocabulary.build` applies it as an override layer after the baseline: update what
exists, insert what is missing, retire what is retired. One file, regenerated like
`episode-labels/`, and a rebuild lands on the vocabulary the catalog actually has.

    python -m catalog.build.export_vocabulary
"""

from __future__ import annotations

import argparse
import json
import sqlite3
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DB = ROOT / "catalog/catalog.db"
OUT = ROOT / "curation/source/vocabulary-current.json"


def export(conn: sqlite3.Connection, out_path: Path) -> dict:
    subjects = [
        {"slug": slug, "name": name, "description": desc, "theme": theme}
        for slug, name, desc, theme in conn.execute(
            """SELECT s.slug, s.name, s.description, t.slug
               FROM subjects s JOIN themes t ON t.id = s.theme_id
               WHERE s.deleted_at IS NULL ORDER BY s.slug""")
    ]
    retired = [
        {"slug": slug, "at": at, "reason": reason}
        for slug, at, reason in conn.execute(
            """SELECT slug, deleted_at, deleted_reason FROM subjects
               WHERE deleted_at IS NOT NULL ORDER BY slug""")
    ]
    payload = {
        "what": ("The catalog's vocabulary as the database currently holds it. An export, "
                 "regenerated by catalog.build.export_vocabulary -- do not edit by hand. "
                 "vocabulary.build applies it over the 148-subject baseline so a rebuild "
                 "carries every subject added, renamed, redescribed or retired since."),
        "subjects": subjects,
        "retired": retired,
    }
    text = json.dumps(payload, ensure_ascii=False, indent=1) + "\n"
    changed = not out_path.exists() or out_path.read_text(encoding="utf-8") != text
    if changed:
        out_path.write_text(text, encoding="utf-8")
    return {"subjects": len(subjects), "retired": len(retired), "written": changed}


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--db", type=Path, default=DB)
    ap.add_argument("--out", type=Path, default=OUT)
    args = ap.parse_args(argv)
    conn = sqlite3.connect(args.db, timeout=30)
    print(json.dumps(export(conn, args.out), indent=1))
    conn.close()
    return 0


if __name__ == "__main__":
    sys.exit(main())
