"""Write the catalog's arcs to `curation/source/`, so a rebuild carries the cascade.

`arcs.seed` rebuilds the 799 arcs the original atlas knew. The Phase 3 arc work -- the
A8 cascade plus agents reading the 66 shows it could not parse -- brought the catalog to
1,809 arcs across 252 shows, wrote `shows.arcs_checked_at` on every show a pass read,
and hung membership on `episodes.arc_id`. All of it db-only: `create_arcs` goes through
the edits door, but creations are not replayable and membership was never logged
per-episode. A rebuild therefore lost 1,010 arcs and every show fell back to depth 2.

Guid-keyed like every other export. `load_arcs` applies it after `arcs.seed`: upsert
each arc by (show, slug), attach members by guid, stamp `arcs_checked_at`.

    python -m catalog.build.export_arcs
"""

from __future__ import annotations

import argparse
import json
import sqlite3
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DB = ROOT / "catalog/catalog.db"
OUT = ROOT / "curation/source/arcs-current.json"


def export(conn: sqlite3.Connection, out_path: Path) -> dict:
    shows: dict[str, dict] = {}
    for slug, checked in conn.execute(
            "SELECT slug, arcs_checked_at FROM shows WHERE deleted_at IS NULL "
            "ORDER BY slug"):
        entry: dict = {}
        if checked:
            entry["arcsCheckedAt"] = checked
        shows[slug] = entry

    for (show, slug, name, kind, conf, desc, deleted_at, deleted_reason,
         src, arc_id) in conn.execute(
            """SELECT sh.slug, a.slug, a.name, a.kind, a.confidence, a.description,
                      a.deleted_at, a.deleted_reason, a.source, a.id
               FROM arcs a JOIN shows sh ON sh.id = a.show_id
               WHERE sh.deleted_at IS NULL ORDER BY sh.slug, a.slug"""):
        members = [g for (g,) in conn.execute(
            "SELECT guid FROM episodes WHERE arc_id = ? AND deleted_at IS NULL "
            "ORDER BY published_at, guid", (arc_id,))]
        arc = {"slug": slug, "name": name, "source": src}
        if kind:
            arc["kind"] = kind
        if conf:
            arc["confidence"] = conf
        if desc:
            arc["description"] = desc
        if deleted_at:
            arc["deletedAt"] = deleted_at
            if deleted_reason:
                arc["deletedReason"] = deleted_reason
        arc["episodes"] = members
        shows.setdefault(show, {}).setdefault("arcs", []).append(arc)

    shows = {k: v for k, v in shows.items() if v}
    payload = {
        "what": ("Arcs as the database currently holds them -- the atlas baseline plus "
                 "the Phase 3 cascade and agent reads. An export, regenerated by "
                 "catalog.build.export_arcs -- do not edit by hand. load_arcs applies "
                 "it after arcs.seed, guid-keyed, so a rebuild keeps all of them and "
                 "arcs_checked_at records which shows were read."),
        "shows": shows,
    }
    text = json.dumps(payload, ensure_ascii=False, indent=1) + "\n"
    changed = not out_path.exists() or out_path.read_text(encoding="utf-8") != text
    if changed:
        out_path.write_text(text, encoding="utf-8")
    n_arcs = sum(len(v.get("arcs") or []) for v in shows.values())
    return {"shows": len(shows), "arcs": n_arcs, "written": changed}


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--db", type=Path, default=DB)
    ap.add_argument("--out", type=Path, default=OUT)
    args = ap.parse_args(argv)
    conn = sqlite3.connect(args.db, timeout=30)
    print(json.dumps(export(conn, args.out), indent=1))
    conn.close()
    return 0


if __name__ == "__main__":
    sys.exit(main())
