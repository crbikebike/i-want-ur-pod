"""Write comb-added episodes to `curation/source/`, so a rebuild has rows to label.

The Phase 3 feed re-read (`admin/api/comb.py`) added thousands of episodes the original
import never had -- three shows sat at an 800-episode cap, and 7am alone was short 1,278.
Those rows went straight into the database; their only upstream source is the gitignored
`feeds/` corpus. A rebuild from a clean checkout therefore came up 3,783 labelled
episodes short across 60 shows and silently dropped 6,091 label rows.

The tracked precedent is `recovered-episodes.json`: episodes committed to git precisely
so the build does not depend on the raw corpus. This does the same for the comb's
additions. The criterion is source-derived, not database-derived: an episode belongs
here when its guid appears in neither `episode-themes/<slug>.json` nor
`recovered-episodes.json` for its show -- exactly the set a rebuild cannot see.

Descriptions and durations ride along, because the gitignored `descriptions/` dir is the
only other place they exist.

    python -m catalog.build.export_episodes
"""

from __future__ import annotations

import argparse
import json
import sqlite3
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DB = ROOT / "catalog/catalog.db"
SOURCE = ROOT / "curation/source"
OUT = SOURCE / "comb-episodes.json"


def _known_guids(source: Path) -> dict[str, set[str]]:
    """Per show slug, every guid a rebuild can already see from tracked files."""
    known: dict[str, set[str]] = {}
    for path in sorted((source / "episode-themes").glob("*.json")):
        if path.name.startswith("_"):
            continue
        data = json.loads(path.read_text(encoding="utf-8"))
        slug = data.get("slug") or path.stem
        known.setdefault(slug, set()).update(
            ep["guid"] for ep in data.get("episodes") or [] if ep.get("guid"))
    recovered_path = source / "recovered-episodes.json"
    if recovered_path.is_file():
        recovered = json.loads(recovered_path.read_text(encoding="utf-8"))
        for slug, eps in (recovered.get("recovered") or {}).items():
            known.setdefault(slug, set()).update(
                ep["guid"] for ep in eps if ep.get("guid"))
    return known


def export(conn: sqlite3.Connection, source: Path, out_path: Path) -> dict:
    known = _known_guids(source)

    combed: dict[str, list[dict]] = {}
    for (slug, guid, title, season, number, etype, published, desc, duration,
         available) in conn.execute(
            """SELECT sh.slug, e.guid, e.title, e.season, e.episode_number,
                      e.episode_type, e.published_at, e.description, e.duration_s,
                      e.available
               FROM episodes e JOIN shows sh ON sh.id = e.show_id
               WHERE e.deleted_at IS NULL AND sh.deleted_at IS NULL
               ORDER BY sh.slug, e.published_at, e.guid"""):
        if guid in known.get(slug, set()):
            continue
        row = {"guid": guid, "title": title, "iso": published,
               "episodeType": etype}
        if season is not None:
            row["season"] = season
        if number is not None:
            row["episodeNumber"] = number
        if desc:
            row["description"] = desc
        if duration is not None:
            row["durationS"] = duration
        if available == 0:
            row["available"] = 0
        combed.setdefault(slug, []).append(row)

    payload = {
        "what": ("Episodes the Phase 3 feed comb added, whose only upstream source is "
                 "the gitignored feeds/ corpus. An export, regenerated by "
                 "catalog.build.export_episodes -- do not edit by hand. load_source "
                 "inserts these after recovered-episodes.json, additively."),
        "shows": len(combed),
        "episodes": sum(len(v) for v in combed.values()),
        "combed": combed,
    }
    text = json.dumps(payload, ensure_ascii=False, indent=1) + "\n"
    changed = not out_path.exists() or out_path.read_text(encoding="utf-8") != text
    if changed:
        out_path.write_text(text, encoding="utf-8")
    return {"shows": payload["shows"], "episodes": payload["episodes"],
            "written": changed}


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--db", type=Path, default=DB)
    ap.add_argument("--source", type=Path, default=SOURCE)
    ap.add_argument("--out", type=Path, default=OUT)
    args = ap.parse_args(argv)
    conn = sqlite3.connect(args.db, timeout=30)
    print(json.dumps(export(conn, args.source, args.out), indent=1))
    conn.close()
    return 0


if __name__ == "__main__":
    sys.exit(main())
