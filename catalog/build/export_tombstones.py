"""Write soft-deletions to `curation/source/`, so a rebuild does not resurrect the dead.

Phase 2 repair work soft-deleted shows (merged duplicates, wrong feeds) and episodes --
4,900-odd rows, many through bulk edits logged as `"key": "empire/*", "rows": 658`. A
wildcard-and-count line is an audit record, not a replayable instruction: it says 658
rows died without naming their guids. So a clean rebuild brought every one of them back.

This exports the tombstones themselves -- (slug, deleted_at, reason) for shows,
(show slug, guid, deleted_at, reason) for episodes -- and `load_source` applies them
after everything is inserted. Guid-keyed like every other export, regenerated the same
way, so what is dead stays dead across rebuilds.

    python -m catalog.build.export_tombstones
"""

from __future__ import annotations

import argparse
import json
import sqlite3
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DB = ROOT / "catalog/catalog.db"
OUT = ROOT / "curation/source/tombstones.json"


def export(conn: sqlite3.Connection, out_path: Path) -> dict:
    shows = [
        {"slug": slug, "at": at, **({"reason": reason} if reason else {})}
        for slug, at, reason in conn.execute(
            """SELECT slug, deleted_at, deleted_reason FROM shows
               WHERE deleted_at IS NOT NULL ORDER BY slug""")
    ]
    episodes: dict[str, list[dict]] = {}
    for slug, guid, at, reason in conn.execute(
            """SELECT sh.slug, e.guid, e.deleted_at, e.deleted_reason
               FROM episodes e JOIN shows sh ON sh.id = e.show_id
               WHERE e.deleted_at IS NOT NULL ORDER BY sh.slug, e.guid"""):
        episodes.setdefault(slug, []).append(
            {"guid": guid, "at": at, **({"reason": reason} if reason else {})})

    payload = {
        "what": ("Soft-deletions the edits log cannot replay -- bulk deletes were logged "
                 "as wildcard-and-count, which names how many rows died but not which. "
                 "An export, regenerated by catalog.build.export_tombstones -- do not "
                 "edit by hand. load_source applies these last, so a rebuild does not "
                 "resurrect merged duplicates and wrong-feed episodes."),
        "shows": shows,
        "episodes": episodes,
    }
    text = json.dumps(payload, ensure_ascii=False, indent=1) + "\n"
    changed = not out_path.exists() or out_path.read_text(encoding="utf-8") != text
    if changed:
        out_path.write_text(text, encoding="utf-8")
    return {"shows": len(shows),
            "episodes": sum(len(v) for v in episodes.values()),
            "written": changed}


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--db", type=Path, default=DB)
    ap.add_argument("--out", type=Path, default=OUT)
    args = ap.parse_args(argv)
    conn = sqlite3.connect(args.db, timeout=30)
    print(json.dumps(export(conn, args.out), indent=1))
    conn.close()
    return 0


if __name__ == "__main__":
    sys.exit(main())
